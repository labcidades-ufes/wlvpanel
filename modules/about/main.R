# Apresentação editorial. Fontes e proveniência visual: docs/about-sources.md.
wlv_about_link <- function(href, label, ...) {
  tags$a(href = href, target = "_blank", rel = "noopener", ..., label)
}
wlv_about_person <- function(name, href, photo = NULL, photo_class = NULL) {
  tags$article(class = paste("wlv-about-person", if (is.null(photo)) "wlv-about-person-text"),
    if (!is.null(photo)) tags$img(src = photo, alt = name, class = photo_class, loading = "lazy"),
    tags$div(tags$h3(name), wlv_about_link(href, l("about2.profile"))))
}

